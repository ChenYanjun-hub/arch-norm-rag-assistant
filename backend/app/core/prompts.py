# 引用核验（agentic RAG · verifier/reflection · 守红线 1 不编造）
# 补规则式治理的缺口：align_modal_verbs 校量词、dangling 查 [N] 角标，
# 但"规范号 / 条文号 / 数字"是否真在 chunks 里有据，规则不做全局核验。
