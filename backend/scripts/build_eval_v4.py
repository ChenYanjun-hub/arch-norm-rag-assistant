# v3.1 字段顺序（v4 沿用，加 v4_status + v4_source）
V31_FIELDS = [
    "id", "scenario", "difficulty", "spec_domain", "query",
    "expected_spec", "expected_clause", "expected_answer_summary",
    "key_elements", "trap_type",
    "v2_status", "v2_remap_reason",
    "v3_status", "v3_target_scenario", "v3_remap_reason",
]
V4_FIELDS = V31_FIELDS + ["v4_status", "v4_source"]


def main() -> None:
    if not SRC.exists():
        print(f"❌ 源文件不存在：{SRC}", file=sys.stderr)
        sys.exit(1)

    # 读 v3.1 50 条
    v31_rows = list(csv.DictReader(open(SRC, encoding="utf-8")))
    print(f"读取 v3.1：{len(v31_rows)} 条")

    # 准备 v4 输出
    out_rows: list[dict[str, str]] = []

    # 1. 沿用 v3.1 全部 50 条（加 v4 字段空值）
    for r in v31_rows:
        row = {f: r.get(f, "") for f in V31_FIELDS}
        row["v4_status"] = "kept_v3_1"
        row["v4_source"] = ""
        out_rows.append(row)

    # 2. 追加 50 条新条目
    for tup in NEW_ROWS:
        qid, dom, diff, scen, spec, clause, query, ans = tup
        row = {
            "id": qid,
            "scenario": scen,
            "difficulty": diff,
            "spec_domain": dom,
            "query": query,
            "expected_spec": spec,
            "expected_clause": clause,
            "expected_answer_summary": ans,
            "key_elements": "",
            "trap_type": "",
            "v2_status": "",
            "v2_remap_reason": "",
            "v3_status": "",
            "v3_target_scenario": "",
            "v3_remap_reason": "",
            "v4_status": "new_q5d1",
            "v4_source": "W5 D1 扩量（温柔挑战 5 步法人工审核通过）",
        }
        out_rows.append(row)

    # 写出
    with open(DST, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=V4_FIELDS)
        w.writeheader()
        w.writerows(out_rows)

    # 统计
    kept = sum(1 for r in out_rows if r["v4_status"] == "kept_v3_1")
    new = sum(1 for r in out_rows if r["v4_status"] == "new_q5d1")
    valid = sum(1 for r in out_rows if r["expected_spec"].strip())
    boundary = sum(1 for r in out_rows if not r["expected_spec"].strip())

    print(f"\n写入 v4：{DST}")
    print(f"  沿用 v3.1   : {kept} 条")
    print(f"  新增 W5 D1  : {new} 条")
    print(f"  总计        : {len(out_rows)} 条")
    print()
    print(f"  ✅ 有效（spec 在库可评测）: {valid} 条")
    print(f"  ⚠️ 边界兜底（fallback 测试）: {boundary} 条")
    print()

    # 按域统计
    from collections import Counter
    by_dom = Counter(r["spec_domain"] for r in out_rows if r["expected_spec"].strip())
    print(f"  按规范域分布（有效条目）:")
    for d, n in by_dom.most_common():
        print(f"    {d}: {n} 条")


if __name__ == "__main__":
    main()
